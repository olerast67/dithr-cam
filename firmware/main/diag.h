// Диагностика без порта: после запуска экрана журнал в UART не идёт (GPIO1
// занят линией SCL). Поэтому последние строки журнала копятся в кольце в
// памяти, при ошибке снимка сохраняются в NVS, а при следующем запуске
// печатаются в порт, пока экран ещё не запущен.
void diag_init(void);
void diag_save(const char *why);
void diag_print_last(void);
