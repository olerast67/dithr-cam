FIRST, LAST = 0x00, 0x7F


def main():
    out = []
    out.append("// Сгенерировано tools/gen_font.py, руками не править.\n")
    out.append('#include "fx.h"\n\n')
    out.append("// 128 глифов по 7 строк, биты 4..0 = столбцы слева направо.\n")
    out.append("const uint8_t fx_font5x7[128][7] = {\n")
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = G.get(ch)
        if rows is None and 'a' <= ch <= 'z':
            rows = G[ch.upper()]
        if rows is None:
            rows = G['?'] if code >= 0x20 else G[' ']
        vals = []
        for r in rows:
            v = 0
            for i, c in enumerate(r):
                if c == '#':
                    v |= 1 << (4 - i)
            vals.append(f"0x{v:02X}")
        label = repr(ch) if 0x20 <= code < 0x7F else f"0x{code:02X}"
        out.append(f"    {{{', '.join(vals)}}}, // {label}\n")
    out.append("};\n")
    dst = Path(__file__).resolve().parent.parent / "firmware" / "components" / "fx" / "font5x7.c"
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("".join(out), encoding="utf-8")
    print("written", dst)


if __name__ == "__main__":
    main()
